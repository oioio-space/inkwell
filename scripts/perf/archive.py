"""Seal raw evidence, require complete repeated benchmark results."""
import hashlib
import json
from pathlib import Path
import re
import statistics

out = Path("docs/perf/baseline/2026-11-02")
readme = """# L0 baseline — 2026-11-02

Machine and exact tool versions: machine.json. Embedded sidecar pins:
internal/sidecar/manifest.json. This is a local amd64 reference, not both CI architectures.

Regenerate: mise run gate -- L0. Heavy steps use scripts/heavy.sh.
HOT_PATHS are read from CLAUDE.md; go test -run '^$' -bench . -benchmem -count 10,
default Go benchtime, followed by benchstat (single baseline, no comparative significance).
Benchmarks use their existing inputs (blob benchmark is 16 MiB, not the proposed 64 MiB).
No application hot paths were changed. No statistically significant improvement is claimed.
PM-1 generator is deterministic, actor/time fixed for Automerge; generated bytes are ignored,
their sizes and hashes are versioned in testdata/perf/corpus.json. History is 500 replacement
delta records over 1,000 files, 20 changed files per version, not an actual Git repository.
A 2 MiB ASCII document, 50,000-character-operation Automerge document, two 2 MiB projects
(1,000/10,000 files), 50 one-MiB blobs (first 20 for memory) are generated.
PM-2: CPU cache eviction, both CI architectures, >=30 UI samples, and noise-control subtraction
are not provided; do not treat diagnostic browser results as acceptance measurements.
PM-3 native aggregate RSS/PSS/VSZ unavailable: see measurements.json.
PM-4: 30 warm Chromium inputs and a detected 120 ms forced-layout control are diagnostic only.
Native WebKit cold/warm sampling is not supplied; censored/8 ms rounded EventTiming entries
cannot provide an exact p95 at the 16 ms boundary. Missing entries are never counted as zero.
Timing reference: https://www.w3.org/TR/event-timing/ (8 ms granularity; minimum reporting threshold 16 ms).
PM-5: thresholds.json freezes the outer-loop decision: Go >+5% AND p<0.05; e2e p95 x1.10.
PERF-START measures current no-plugin cold app process to usable Chromium editor (warm OS caches).
Plugin load deferred to Fondations-extensibles; PERF-MEM and native PERF-TYPE deferred to L2.
Chromium PERF-TYPE remains proxy, never native certification. See thresholds.json for censor bounds.
Regression guard: python3 scripts/perf/regression.py --bench FRESH_GO --e2e FRESH_P95_JSON.
FRESH_P95_JSON maps PERF-START/PERF-TYPE to p95_ms; same measurement scope required.
PERF-RELAY-ALLOC remains 1 alloc/op (48 B) versus the unchanged zero target.
Known failures F10/F11/F12 are retained in gates/L0.json, never waived.
SHA256SUMS covers all archived files except itself; corpus.json covers generated inputs.
"""
quality = json.loads((out / "reference-quality.json").read_text())
readme += "\nReference quality: " + quality['status'] + ". GOMAXPROCS=20; -count=20 -benchmem.\n"
readme += "Quiet acquisition: INKWELL_HEAVY_SLOTS=1 scripts/heavy.sh python3 scripts/perf/reference.py; holds all existing heavy slots.\n"
readme += "Reject CV >10% (sample SD/mean of ns/op), up to three attempts; all attempts retained.\n"
for attempt in quality['attempts']:
    readme += f"\nAttempt {attempt['attempt']}: {attempt['status']}; load before {attempt['load_before']}, after {attempt['load_after']}.\n"
    readme += "CPU MHz before: " + ', '.join(x.split(':')[-1].strip() for x in attempt['cpu_frequency_before']) + "; after: " + ', '.join(x.split(':')[-1].strip() for x in attempt['cpu_frequency_after']) + ".\n"
    readme += "CV (%): " + ', '.join(f"{k}={v:.2f}" for k,v in attempt['cv_percent'].items()) + ".\n"
readme += "Go thresholds store only the reference SHA256 and significance rule; the guard verifies the hash before comparison.\n"
(out / "README.md").write_text(readme)
raw = (out / "go-bench.txt").read_text()
samples = {}
for line in raw.splitlines():
    match = re.match(r"(Benchmark\S+)\s+\d+\s+([0-9.]+) ns/op.*?([0-9.]+) B/op\s+([0-9.]+) allocs/op", line)
    if match:
        samples.setdefault(match[1], []).append(tuple(map(float, match.groups()[1:])))
summary = {name: {"samples": len(rows),
    "median_ns_per_op": statistics.median(r[0] for r in rows),
    "median_bytes_per_op": statistics.median(r[1] for r in rows),
    "median_allocs_per_op": statistics.median(r[2] for r in rows)}
    for name, rows in samples.items()}
(out / "summary.json").write_text(json.dumps(summary, indent=2)+"\n")
(out / "SHA256SUMS").write_text("".join(
    hashlib.sha256(p.read_bytes()).hexdigest()+"  "+p.name+"\n"
    for p in sorted(out.iterdir()) if p.is_file() and p.name != "SHA256SUMS"))
raw = (out / "go-bench.txt").read_text()
counts = {}
for line in raw.splitlines():
    if re.match(r"Benchmark\S+\s+\d+\s+", line):
        name = line.split()[0]
        counts[name] = counts.get(name, 0)+1
assert counts and min(counts.values()) >= 10, counts
assert all(f"pkg: github.com/oioio-space/inkwell/{p}" in raw for p in
           ["internal/blob", "internal/transport/frame", "internal/transport/mux", "internal/app"])
assert (out / "benchstat.txt").stat().st_size
assert json.loads((out / "measurements.json").read_text())
print("Archive sealed; named deferrals and proxy caveats retained in manifest")
