#!/usr/bin/env python3
"""Review trace syscall names and render architecture-numbered seccomp tables.
Usage: python3 scripts/sidecar-allowlist.py TRACE_DIR
Run sidecar-trace.py on each Linux CI architecture and review the union.
"""
from pathlib import Path
import re
import subprocess
import sys

check = sys.argv[1] == "--check"
traces = Path(sys.argv[2] if check else sys.argv[1])
names = set((traces / 'syscalls.txt').read_text().split())
# Denied regardless of observation. Argument-filtered calls stay in the table.
blocked = {'socket', 'connect', 'bind', 'sendto', 'sendmsg', 'sendmmsg', 'kill',
           'tkill', 'clone3', 'io_uring_setup', 'userfaultfd', 'perf_event_open',
           'modify_ldt'}
# Go runtime in launcher/test helpers after filter installation; arm64 uses
# epoll_pwait in place of epoll_wait. These are explicit reviewed additions.
runtime = {'read', 'write', 'close', 'execve', 'exit', 'exit_group', 'futex',
           'getpid', 'gettid', 'tgkill', 'rt_sigaction', 'rt_sigprocmask',
           'rt_sigreturn', 'sigaltstack', 'mmap', 'mprotect', 'munmap', 'madvise',
           'sched_yield', 'nanosleep', 'clock_gettime', 'epoll_pwait', 'epoll_ctl',
           'epoll_create1', 'fcntl', 'clone', 'wait4', 'restart_syscall',
           'sched_getaffinity', 'getppid', 'getuid', 'geteuid', 'getgid', 'getegid',
           'newfstatat', 'readlinkat', 'faccessat', 'faccessat2', 'statfs', 'fstatfs',
           'pipe2', 'dup3', 'ftruncate', 'waitid'}
allowed = (names | runtime) - blocked
out = Path('internal/sidecar')
if check:
    missing = allowed - set((out / 'syscalls-linux.txt').read_text().split())
    if missing:
        raise SystemExit('Unreviewed trace syscalls: ' + ', '.join(sorted(missing)))
    raise SystemExit(0)
(out / 'syscalls-linux.txt').write_text('\n'.join(sorted(allowed)) + '\n')
module = subprocess.check_output(['go', 'list', '-m', '-f', '{{.Dir}}', 'golang.org/x/sys'], text=True).strip()
for arch in ('amd64', 'arm64'):
    source = (Path(module) / 'unix' / f'zsysnum_linux_{arch}.go').read_text()
    numbers = dict(re.findall(r'SYS_(\w+)\s*=\s*(\d+)', source))
    lines = ['// Code generated by scripts/sidecar-allowlist.py; DO NOT EDIT.',
             '// Trace-derived list plus documented runtime portability additions.',
             'package sidecar', '', 'var allowedSyscalls = []uint32{']
    for name in sorted(allowed):
        if name.upper() in numbers:
            lines.append(f'\t{numbers[name.upper()]}, // {name}')
    lines.append('}\n')
    (out / f'syscalls_linux_{arch}.go').write_text('\n'.join(lines))
subprocess.run(['gofmt', '-w', str(out / 'syscalls_linux_amd64.go'),
                str(out / 'syscalls_linux_arm64.go')], check=True)
