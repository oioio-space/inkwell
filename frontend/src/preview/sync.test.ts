import { describe, expect, it } from "vitest";
import type { Anchor } from "./protocol";
import { align, lineAt, normalize, pairUp, placeOf, sourceBlocks } from "./sync";

const SOURCE = `#set text(lang: "fr")
#set page(margin: 2cm)

= Titre un <a>
Bonjour *monde*, ceci est
un paragraphe sur deux lignes.

\`\`\`typ
= pas un titre
\`\`\`

// un commentaire

== Deux
Suite du texte — avec « guillemets » et un #emph[mot].
#pagebreak()
- première puce
- seconde puce

= Trois
Fin.
`;

const anchors: Anchor[] = [
  { heading: true, page: 1, x: 70, y: 70, text: "Titre un" },
  {
    heading: false,
    page: 1,
    x: 70,
    y: 100,
    text: "Bonjour monde, ceci est un paragraphe sur deux lignes.",
  },
  { heading: true, page: 2, x: 70, y: 70, text: "Deux" },
  {
    heading: false,
    page: 2,
    x: 70,
    y: 95,
    text: "Suite du texte — avec « guillemets » et un mot.",
  },
  { heading: false, page: 2, x: 70, y: 400, text: "première puce" },
  { heading: true, page: 3, x: 70, y: 70, text: "Trois" },
  { heading: false, page: 3, x: 70, y: 90, text: "Fin." },
];

describe("source blocks", () => {
  it("PRV-60 reads headings and paragraphs, skipping code fences, comments and rules", () => {
    expect(sourceBlocks(SOURCE).map((b) => [b.line, b.heading])).toEqual([
      [4, true],
      [5, false],
      [14, true],
      [15, false],
      [17, false],
      [20, true],
      [21, false],
    ]);
  });

  it("PRV-60 a Markdown source has headings too", () => {
    const b = sourceBlocks("# Un titre\n\nDu texte.\n\n## Sous-titre\n");
    expect(b.map((x) => [x.line, x.heading])).toEqual([
      [1, true],
      [3, false],
      [5, true],
    ]);
  });

  it("PRV-60 CRLF and a missing final newline change nothing", () => {
    expect(sourceBlocks("= A b c\r\nTexte ici.").map((b) => b.line)).toEqual([1, 2]);
  });

  it("PRV-60 a block comment hides its lines", () => {
    expect(sourceBlocks("/*\n= caché\n*/\n= Visible\n").map((b) => b.line)).toEqual([4]);
  });

  it("PRV-61 text is compared by its letters and digits only", () => {
    expect(normalize("« Café — 2 !* »")).toBe("café2");
    expect(normalize("日本語 テスト")).toBe("日本語テスト");
  });
});

describe("pairing", () => {
  const pairs = pairUp(SOURCE, anchors);

  it("PRV-62 pairs each anchor with the block that says the same, in order", () => {
    expect(pairs.map((p) => [p.line, p.anchor.page, p.anchor.y])).toEqual([
      [4, 1, 70],
      [5, 1, 100],
      [14, 2, 70],
      [15, 2, 95],
      [17, 2, 400],
      [20, 3, 70],
      [21, 3, 90],
    ]);
  });

  it("PRV-62 text generated by code has no block and is skipped without losing the others", () => {
    const withGenerated: Anchor[] = [
      anchors[0] as Anchor,
      { heading: false, page: 1, x: 70, y: 80, text: "Texte venu d'un calcul" },
      ...anchors.slice(1),
    ];
    expect(pairUp(SOURCE, withGenerated)).toHaveLength(7);
  });

  it("PRV-62 a repeated sentence is paired in order, not all with the first", () => {
    const src = "Même phrase ici.\n\nMême phrase ici.\n";
    const a: Anchor[] = [
      { heading: false, page: 1, x: 0, y: 10, text: "Même phrase ici." },
      { heading: false, page: 1, x: 0, y: 50, text: "Même phrase ici." },
    ];
    expect(pairUp(src, a).map((p) => p.line)).toEqual([1, 3]);
  });

  it("PRV-62 a heading never pairs with a paragraph of the same words", () => {
    const a: Anchor[] = [{ heading: true, page: 1, x: 0, y: 10, text: "Bonjour monde" }];
    expect(align(sourceBlocks("Bonjour monde\n"), a)).toEqual([]);
  });

  it("PRV-62 nothing to pair gives nothing", () => {
    expect(pairUp("", anchors)).toEqual([]);
    expect(pairUp(SOURCE, [])).toEqual([]);
  });

  it("PRV-63 source to page: the caret's paragraph, or the one above it", () => {
    expect(placeOf(pairs, 5)).toEqual({ page: 1, y: 100 });
    expect(placeOf(pairs, 6)).toEqual({ page: 1, y: 100 }); // second line of the paragraph
    expect(placeOf(pairs, 8)).toEqual({ page: 1, y: 100 }); // in the code fence, below it
    expect(placeOf(pairs, 14)).toEqual({ page: 2, y: 70 });
    expect(placeOf(pairs, 1)).toEqual({ page: 1, y: 70 }); // above everything: the first block
    expect(placeOf(pairs, 999)).toEqual({ page: 3, y: 90 });
    expect(placeOf([], 3)).toBeUndefined();
  });

  it("PRV-64 page to source: the block hit, the one above it, or the first of the page", () => {
    expect(lineAt(pairs, 1, 105)).toBe(5);
    expect(lineAt(pairs, 1, 72)).toBe(4);
    expect(lineAt(pairs, 1, 5)).toBe(4); // above the first block of the page
    expect(lineAt(pairs, 2, 500)).toBe(17);
    expect(lineAt(pairs, 2, 200)).toBe(15);
    expect(lineAt(pairs, 3, 0)).toBe(20);
    expect(lineAt(pairs, 4, 0)).toBeUndefined();
  });

  it("PRV-65 a source edited since the compilation still pairs what has not changed", () => {
    const edited = `Une ligne ajoutée avant tout.\n\n${SOURCE}`;
    const p = pairUp(edited, anchors);
    expect(p).toHaveLength(7);
    expect(p[0]?.line).toBe(6); // the heading moved down by two lines
  });
});
